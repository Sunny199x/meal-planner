CREATE TABLE "recipes" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	"origin" text NOT NULL,
	"file_slug" text,
	"edited_in_app" boolean DEFAULT false NOT NULL,
	"is_template" boolean DEFAULT false NOT NULL,
	"title" text NOT NULL,
	"source" text NOT NULL,
	"source_url" text,
	"servings" integer NOT NULL,
	"time_total_min" integer NOT NULL,
	"time_active_min" integer,
	"cuisine" text NOT NULL,
	"diet" text NOT NULL,
	"main_protein" text,
	"freezer_friendly" boolean NOT NULL,
	"good_as_leftovers" boolean NOT NULL,
	"tags" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"ingredients" jsonb NOT NULL,
	"instructions" jsonb NOT NULL,
	"make_ahead" jsonb NOT NULL,
	"notes" text,
	"is_favourite" boolean DEFAULT false NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "recipes_file_slug_unique" UNIQUE("file_slug")
);
